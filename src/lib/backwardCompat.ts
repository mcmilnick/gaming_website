// Which "to" consoles each "from" console can be checked against, and in
// what order they should list. Not every pair of consoles is a real
// backward-compatibility relationship (most aren't), so the "To" dropdown
// only ever offers what's defined here, instead of every console in the
// catalog - that's what keeps a user from picking a pairing that doesn't
// mean anything (e.g. "PlayStation 2 to Xbox 360").
//
// Xbox One and Xbox Series X|S are written out as separate targets for every
// "from" console below, even where (today) they'd always give the same
// answer - that's intentional. It keeps the dropdown saying what it means
// (a Series X|S owner shouldn't have to read "Xbox One" and guess it also
// covers them), and it leaves room for a target that only diverges for one
// "from" console (say, a title Optimized for Series X|S that an Xbox One
// can't run at all) without having to restructure this later.
export const BACKWARD_COMPAT_TARGETS: Record<string, string[]> = {
  "Xbox 360": ["Xbox One", "Xbox Series X|S"],
  "Xbox One": ["Xbox Series X|S"],
  "Xbox": ["Xbox 360", "Xbox One", "Xbox Series X|S"],
};

export const BACKWARD_COMPAT_FROM_CONSOLES = Object.keys(BACKWARD_COMPAT_TARGETS);

// Normalizing once per list and caching the result means checking a whole
// console's worth of games (thousands, for the main catalog) is a plain Set
// lookup per game instead of re-normalizing the reference list every time.
// Keyed by "allow:<key>" / "block:<key>" so the two lists can never collide
// even if the same key ever ended up in both.
const normalizedSetCache = new Map<string, Set<string>>();

function getNormalizedSet(cacheKey: string, titles: string[]): Set<string> {
  const cached = normalizedSetCache.get(cacheKey);
  if (cached) return cached;
  const set = new Set(titles.map(normalizeForSearch));
  normalizedSetCache.set(cacheKey, set);
  return set;
}

// Looks up the right title list for a (from, to) pair: the specific
// "<from>|<to>" override if one exists (Original Xbox -> Xbox 360 needs
// this, see the comment on BACKWARD_COMPATIBLE_TITLES), otherwise the plain
// "<from>" list that applies to all of that console's targets.
function resolveTitles(map: Record<string, string[]>, fromConsole: string, toConsole: string): string[] | undefined {
  return map[`${fromConsole}|${toConsole}`] ?? map[fromConsole];
}

// A "from" console is either an allowlist (only these titles are
// compatible - the Xbox 360 and Original Xbox cases, where the compatible
// set is small) or a blocklist (everything is compatible except these - the
// Xbox One case, where the excluded set is small). A console not in either
// list isn't supported yet and reports nothing as compatible.
export function isBackwardCompatible(fromConsole: string, toConsole: string, title: string): boolean {
  const normalized = normalizeForSearch(title);

  const allowlist = resolveTitles(BACKWARD_COMPATIBLE_TITLES, fromConsole, toConsole);
  if (allowlist) return getNormalizedSet(`allow:${fromConsole}|${toConsole}`, allowlist).has(normalized);

  const blocklist = resolveTitles(BACKWARD_COMPAT_EXCLUDED_TITLES, fromConsole, toConsole);
  if (blocklist) return !getNormalizedSet(`block:${fromConsole}|${toConsole}`, blocklist).has(normalized);

  return false;
}
